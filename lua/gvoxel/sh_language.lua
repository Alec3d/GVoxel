V.Translations = translations
local supported = {en=true, fr=true, ru=true, es=true, it=true, de=true}
function V.ValidLanguage(code)
    return supported[code] and code or "en"
end
function V.Localize(key, code, ...)
    local entry = translations[key]
    local text = entry and (entry[V.ValidLanguage(code)] or entry.en) or key
    if select("#", ...) > 0 then return string.format(text, ...) end
    return text
end
local selected = "en"
function V.GetLanguage() return selected end
function V.L(key, ...) return V.Localize(key, selected, ...) end
